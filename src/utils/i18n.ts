export const getTranslation = (
  lang: Language | string = 'en',
  key: string,
  params?: Record<string, string | number>
): string => {
  const safeLang = (lang === 'ar' ? 'ar' : 'en') as Language;
  let text = translations[safeLang]?.[key] || translations.en[key] || key;
  if (params) {
    Object.keys(params).forEach((paramKey) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(params[paramKey]));
    });
  }
  return text;
};

export const isRTL = (lang?: Language | string): boolean => {
  return lang === 'ar';
};
